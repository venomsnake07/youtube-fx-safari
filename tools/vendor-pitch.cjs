/* Regenerate the embedded, unchanged WASM from signalsmith-stretch@1.3.2.
 * Usage: npm pack signalsmith-stretch@1.3.2; tar -xf signalsmith-stretch-1.3.2.tgz
 *        node tools/vendor-pitch.cjs path/to/package/SignalsmithStretch.mjs
 * This is a developer tool; users install the ZIP without a build step.
 */
'use strict';
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const source = fs.readFileSync(process.argv[2], 'utf8');
const encoded = source.match(/data:application\/octet-stream;base64,([A-Za-z0-9+/=]+)/)?.[1];
if (!encoded) throw new Error('No embedded WASM found in the pinned upstream package.');
const sha = crypto.createHash('sha256').update(Buffer.from(encoded, 'base64')).digest('hex');
if (sha !== '83869197b3c5ebf9fc8c517a1586aef1ecf77404842218d62b9c0e82882d8ca3') throw new Error('Upstream WASM checksum does not match the audited 1.3.2 release.');
const target = fs.existsSync(path.join(__dirname, '../manifest.json')) ? path.join(__dirname, '..') : path.join(__dirname, '../extension');
const code = `/* Signalsmith Stretch 1.3.2, MIT License.
 * Copyright (c) 2022 Geraint Luff / Signalsmith Audio Ltd.
 * Unchanged upstream WASM; see THIRD-PARTY-NOTICES.md.
 * SHA-256: ${sha}
 * Generated by tools/vendor-pitch.cjs. No downloaded or evaluated JS.
 */
(() => {
  'use strict';
  const encoded = '${encoded}';
  let compiled;
  function create() {
    if (!compiled) {
      // AudioWorkletGlobalScope does not consistently provide atob in Safari.
      const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
      const lookup = new Uint8Array(128);
      for (let i = 0; i < alphabet.length; i++) lookup[alphabet.charCodeAt(i)] = i;
      const padding = encoded.endsWith('==') ? 2 : encoded.endsWith('=') ? 1 : 0;
      const bytes = new Uint8Array(encoded.length / 4 * 3 - padding);
      let position = 0;
      for (let i = 0; i < encoded.length; i += 4) {
        const value = (lookup[encoded.charCodeAt(i)] << 18) | (lookup[encoded.charCodeAt(i + 1)] << 12)
          | (lookup[encoded.charCodeAt(i + 2)] << 6) | lookup[encoded.charCodeAt(i + 3)];
        bytes[position++] = value >>> 16;
        if (position < bytes.length) bytes[position++] = (value >>> 8) & 255;
        if (position < bytes.length) bytes[position++] = value & 255;
      }
      compiled = new WebAssembly.Module(bytes);
    }
    let memory;
    const instance = new WebAssembly.Instance(compiled, {a: {
      // Emscripten imports: random_get, resize_heap, memcpy, abort. Randomness
      // seeds an internal C++ generator; it is unrelated to user information.
      a: (pointer, count) => {
        const bytes = new Uint8Array(memory.buffer, pointer, count);
        for (let i = 0; i < count; i++) bytes[i] = Math.random() * 256;
        return 0;
      },
      b: requested => {
        const pages = Math.ceil((requested - memory.buffer.byteLength) / 65536);
        if (pages <= 0) return 1;
        try {memory.grow(pages); return 1;} catch {return 0;}
      },
      c: (destination, source, count) => {new Uint8Array(memory.buffer).copyWithin(destination, source, source + count);},
      d: () => {throw new Error('Stereo pitch kernel stopped.');}
    }});
    const e = instance.exports; memory = e.e;
    e.f(); e.y(0, 0);
    // Export names are pinned to the verified upstream binary above.
    return {memory, api: {
      setBuffers: e.h, blockSamples: e.i, intervalSamples: e.j,
      inputLatency: e.k, outputLatency: e.l, reset: e.m,
      configure: e.p, setTransposeSemitones: e.r, process: e.w
    }};
  }
  globalThis.YouTubeFXPitchKernel = Object.freeze({version: '1.3.2', create});
})();
`;
fs.writeFileSync(path.join(target, 'pitch-kernel.js'), code);
console.log('Vendored Signalsmith Stretch 1.3.2:', sha);
